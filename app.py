
from pathlib import Path
import io
import json
from functools import lru_cache

import joblib
import numpy as np
import pandas as pd

from flask import Flask, jsonify, render_template, request
from werkzeug.exceptions import RequestEntityTooLarge

from train import ecg_features, quality


ROOT = Path(__file__).resolve().parent
MODEL = ROOT / "artifacts" / "models.joblib"
METRICS = ROOT / "artifacts" / "metrics.json"

app = Flask(__name__)
app.config["MAX_CONTENT_LENGTH"] = 2 * 1024 * 1024


@app.get("/")
@app.get("/dashboard")
def dashboard():
    return render_template("dashboard.html", active="dashboard")


@app.get("/prediction")
def prediction_page():
    return render_template("prediction.html", active="prediction")


@app.get("/models")
def models_page():
    return render_template("models.html", active="models")


@app.get("/about")
def about_page():
    return render_template("about.html", active="about")


@app.get("/api/status")
def status():
    return jsonify({
        "trained": MODEL.is_file(),
        "message": (
            "Model ready"
            if MODEL.is_file()
            else "Training required"
        )
    })


@app.get("/api/metrics")
def model_metrics():
    if not METRICS.is_file():
        return jsonify({
            "trained": False,
            "message": "Train models to display evaluation metrics."
        })

    return jsonify({
        "trained": True,
        **json.loads(METRICS.read_text(encoding="utf-8"))
    })


@lru_cache(maxsize=1)
def load_model():
    # Only load trusted models generated by your training script.
    return joblib.load(MODEL)


def score(models, values, labels):
    return np.array([
        models[label].predict_proba(values)[0, 1]
        for label in labels
    ])


@app.post("/api/predict")
def predict():
    if not MODEL.is_file():
        return jsonify({
            "error": "Train the model first using python train.py"
        }), 409

    if "ecg" not in request.files:
        return jsonify({
            "error": "Select an ECG CSV recording."
        }), 400

    try:
        uploaded = request.files["ecg"]

        if not uploaded.filename.lower().endswith(".csv"):
            raise ValueError("Only CSV files are accepted")

        x = pd.read_csv(
            io.BytesIO(uploaded.read()),
            header=None
        ).to_numpy(dtype=float)

        features = ecg_features(x).reshape(1, -1)

        def number(key):
            value = request.form.get(key, "").strip()
            result = float(value) if value else np.nan

            if np.isinf(result):
                raise ValueError("Invalid " + key)

            return result

        c = np.array([[
            number(k)
            for k in ["age", "sex", "height", "weight"]
        ]], dtype=float)

        age, sex, height, weight = c[0]

        if np.isfinite(age) and not 0 <= age <= 110:
            raise ValueError("Invalid age")

        if np.isfinite(sex) and sex not in [0, 1]:
            raise ValueError("Sex must be 0 or 1")

        if np.isfinite(height) and not 0 < height <= 250:
            raise ValueError("Invalid height")

        if np.isfinite(weight) and not 0 < weight <= 400:
            raise ValueError("Invalid weight")

        if not np.isfinite(c).any():
            raise ValueError("Enter at least one metadata field")

        bundle = load_model()
        labels = bundle["labels"]

        pe = score(bundle["ecg"], features, labels)
        pc = score(bundle["clinical"], c, labels)

        eq = quality(x)
        cq = float(np.isfinite(c).mean())

        alpha = np.asarray(bundle["alpha"], dtype=float)

        weights = (
            alpha * eq
            / (
                alpha * eq
                + (1 - alpha) * cq
                + 1e-8
            )
        )

        fused = weights * pe + (1 - weights) * pc

        thresholds = np.asarray(
            bundle["thresholds"],
            dtype=float
        )

        return jsonify({
            "labels": labels,
            "ecg": pe.tolist(),
            "clinical": pc.tolist(),
            "fixed": (0.5 * pe + 0.5 * pc).tolist(),
            "fused": fused.tolist(),
            "predicted_labels": [
                labels[i]
                for i, value in enumerate(fused)
                if value >= thresholds[i]
            ],
            "thresholds": thresholds.tolist(),
            "ecg_quality": eq,
            "metadata_completeness": cq,
            "ecg_weight": float(weights.mean()),
            "ecg_weights": weights.tolist(),
            "lead_ii": x[:, 1][::4].tolist(),
            "note": (
                "Uncalibrated diagnostic scores. "
                "Not future cardiovascular risk."
            )
        })

    except (ValueError, TypeError, pd.errors.ParserError) as error:
        return jsonify({"error": str(error)}), 400

    except Exception:
        app.logger.exception("Prediction failure")
        return jsonify({
            "error": "Prediction failed. Check the Flask terminal."
        }), 500


@app.errorhandler(RequestEntityTooLarge)
def oversized(error):
    return jsonify({
        "error": "CSV exceeds the 2 MB limit"
    }), 413


if __name__ == "__main__":
    app.run(
        host="127.0.0.1",
        port=5000,
        debug=True
    )
